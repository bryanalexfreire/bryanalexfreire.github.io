  function applyTranslations(lang){
    const map = translations[lang] || translations.es;
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if(!key) return;
      const text = map[key];
      if(typeof text === 'undefined') return;
      if(el.tagName.toLowerCase() === 'input' || el.tagName.toLowerCase() === 'textarea'){
        el.placeholder = text;
      } else {
        el.textContent = text;
      }
    });
    // Update href for elements that have per-language URL variants
    document.querySelectorAll('[data-lang-href-' + lang + ']').forEach(el => {
      el.href = el.getAttribute('data-lang-href-' + lang);
    });
  }

  function setActiveLangButton(lang){
    document.querySelectorAll('.lang-btn').forEach(btn => {
      btn.classList.toggle('active', btn.dataset.lang === lang);
    });
  }

  document.addEventListener('DOMContentLoaded', function(){
    const saved = localStorage.getItem('site-lang') || 'es';
    applyTranslations(saved);
    setActiveLangButton(saved);

    document.querySelectorAll('.lang-btn').forEach(btn => {
      btn.addEventListener('click', () => {
        const lang = btn.dataset.lang || 'es';
        localStorage.setItem('site-lang', lang);
        applyTranslations(lang);
        setActiveLangButton(lang);
      });
    });
  });
